export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 20,
  color = colors.text,
  strokeWidth = 2,
  fill = 'none',
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  /** Solid icons, e.g. a filled star for ratings and favourites. */
  fill?: string;
}) {
  const Glyph = ICONS[name];
  return <Glyph size={size} color={color} strokeWidth={strokeWidth} fill={fill} />;
}

export function isIconName(value: string | null | undefined): value is IconName {
  return value != null && value in ICONS;
}
